const express=require("express")
const app=express()
const jwt=require("jsonwebtoken")
const cors=require("cors")
const bodyParser=require("body-parser")
const multer=require('multer')
const storage = multer.diskStorage({
  destination: function (req, file, cb) {
    cb(null, './Uploads')
  },
  filename: function (req, file, cb) {
    const uniqueSuffix = Date.now() + '-' + Math.round(Math.random() * 1E9)
    cb(null,'-' + uniqueSuffix+ file.originalname)
  }
})
const upload = multer({ storage: storage })
const connect=require("./db")
const userModel=require("./models/users.Model")
const contactModel=require("./models/contact.Model")
const doctorModel=require("./models/doctor.model")
const patientmodel=require("./models/Patient.Model")
const appointmentmodel=require("./models/appointment.Model")
const {contact}=require("./Controllers/contact.Controller")
const {addDoctor,deleteDoctor,allDoctors,updateDoctor}=require("./Controllers/doctor.Controller")
const {appointments,allAppointments}=require("./Controllers/appointments.Controller")
const {patient,allPatients,singlePatient}=require("./Controllers/patient.Controllers")
connect()
const loginRoutes=require("./Routes/Authentication")
app.use(bodyParser.json())
app.use(cors())
app.use(express.static(__dirname+"/Public"))
app.use(express.json())
app.use("/login",loginRoutes)
app.get("/",(req,res)=>{
    res.send({msg:"Hello all"})
})
app.post("/contact",contact)
app.post("/addDoctor",upload.single("image"),addDoctor)
app.get("/doctors",allDoctors)
app.delete("/deleteDoctor",deleteDoctor)
app.post("/patients",patient)
app.post("/appointmentBooking",appointments)
app.get("/allPatients",allPatients)
app.get("/allAppointments",allAppointments)
app.post("/updateDoctor",updateDoctor)
app.get("/patient/:id",singlePatient)
app.listen(3600,()=>{
    console.log("Server is running successfully")
})